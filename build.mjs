/* Static builder: composes pages into public/, generates sitemap.xml + robots.txt. */
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";
import { layout, SITE } from "./src/chrome.mjs";
import { home } from "./src/pages/home.mjs";
import { host } from "./src/pages/host.mjs";
import { about } from "./src/pages/about.mjs";
import { contact } from "./src/pages/contact.mjs";
import { search } from "./src/pages/search.mjs";
import { property } from "./src/pages/property.mjs";
import { riverUnion } from "./src/pages/riverunion.mjs";
import { notfound } from "./src/pages/notfound.mjs";
import { hostFlow } from "./src/pages/hostflow.mjs";
import { privacy, cookies, terms } from "./src/pages/legal.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(__dirname, "public");

/* Short content hashes for cache-busting long-lived static assets. */
const hashFile = (rel) =>
  crypto.createHash("sha256").update(fs.readFileSync(path.join(OUT, rel))).digest("hex").slice(0, 10);
const ASSETS = ["css", "js"].flatMap((dir) =>
  fs.readdirSync(path.join(OUT, "assets", dir)).filter((f) => /\.(css|js)$/.test(f)).map((f) => `/assets/${dir}/${f}`));
const versions = Object.fromEntries(ASSETS.map((a) => [a, hashFile(a.slice(1))]));

/* Register every page here. slug "" => site root. */
const PAGES = [home, host, hostFlow, search, property, riverUnion, about, contact, privacy, cookies, terms, notfound];

let written = [];
for (const page of PAGES) {
  let html = layout(page);
  // version css/js so they can be cached immutably
  for (const a of ASSETS) html = html.split(`"${a}"`).join(`"${a}?v=${versions[a]}"`);
  let file;
  if (page.file) {
    file = path.join(OUT, page.file); // e.g. 404.html at root
  } else {
    const dir = page.slug ? path.join(OUT, page.slug) : OUT;
    fs.mkdirSync(dir, { recursive: true });
    file = path.join(dir, "index.html");
  }
  fs.writeFileSync(file, html, "utf8");
  written.push(path.relative(OUT, file).replace(/\\/g, "/"));
}

/* Pages eligible for the sitemap (exclude 404 / noindex). */
const indexable = PAGES.filter((p) => !p.file && !p.noindex);

/* sitemap.xml */
const today = new Date().toISOString().slice(0, 10);
const urls = indexable.map((p) => {
  const loc = SITE.url + "/" + (p.slug ? p.slug + "/" : "");
  const pr = p.slug === "" ? "1.0" : p.slug.startsWith("legal") ? "0.3" : "0.8";
  return `  <url><loc>${loc}</loc><lastmod>${today}</lastmod><priority>${pr}</priority></url>`;
}).join("\n");
fs.writeFileSync(
  path.join(OUT, "sitemap.xml"),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`,
  "utf8"
);

/* robots.txt */
fs.writeFileSync(
  path.join(OUT, "robots.txt"),
  `User-agent: *\nAllow: /\n\nSitemap: ${SITE.url}/sitemap.xml\n`,
  "utf8"
);

/* CSP hashes for inline JSON-LD (keeps script-src strict). Must match the exact
   bytes head() emits: JSON.stringify(obj) with no spacing. */
const hashes = new Set();
for (const p of PAGES) for (const o of p.jsonld || []) {
  hashes.add("sha256-" + crypto.createHash("sha256").update(JSON.stringify(o), "utf8").digest("base64"));
}
fs.writeFileSync(
  path.join(__dirname, "src", "generated-csp.js"),
  `// AUTO-GENERATED by build.mjs — do not edit by hand.\nexport const JSONLD_HASHES = ${JSON.stringify([...hashes], null, 2)};\n`,
  "utf8"
);

console.log(`Built ${written.length} page(s):`);
written.forEach((w) => console.log("  /" + w));
console.log("  sitemap.xml, robots.txt");
