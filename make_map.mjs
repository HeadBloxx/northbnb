/* One-off generator for src/mapdata.mjs: real land borders for the host-flow map.
   Uses Natural Earth 10m (public domain), whose country polygons follow the coastline.
   (OpenStreetMap country relations include territorial waters, which draws land out
   into the sea, so they are not used.) Shapes are projected with the same equirectangular
   constants the flow uses, clipped to the area the map can show, and simplified.
   Run: node make_map.mjs */
import fs from "node:fs";

const NE = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/";
const COUNTRIES = {
  mne: "Montenegro",
  alb: "Albania",
  kos: "Kosovo",
  srb: "Serbia",
  bih: "Bosnia and Herzegovina",
  hrv: "Croatia",
  mkd: "North Macedonia",
};

/* Must match PROJ in src/pages/hostflow.mjs and host-flow.js */
const PROJ = { lon0: 18.35, kx: 147, ox: 10, lat0: 43.62, ky: 200, oy: 80 };
const px = (lon, lat) => [(lon - PROJ.lon0) * PROJ.kx + PROJ.ox, (PROJ.lat0 - lat) * PROJ.ky + PROJ.oy];

const WIN = { x0: -420, y0: -280, x1: 760, y1: 760 };

/* Sutherland-Hodgman against the window rectangle */
function clip(ring) {
  const edges = [
    [(p) => p[0] >= WIN.x0, (a, b) => [WIN.x0, a[1] + ((b[1] - a[1]) * (WIN.x0 - a[0])) / (b[0] - a[0])]],
    [(p) => p[0] <= WIN.x1, (a, b) => [WIN.x1, a[1] + ((b[1] - a[1]) * (WIN.x1 - a[0])) / (b[0] - a[0])]],
    [(p) => p[1] >= WIN.y0, (a, b) => [a[0] + ((b[0] - a[0]) * (WIN.y0 - a[1])) / (b[1] - a[1]), WIN.y0]],
    [(p) => p[1] <= WIN.y1, (a, b) => [a[0] + ((b[0] - a[0]) * (WIN.y1 - a[1])) / (b[1] - a[1]), WIN.y1]],
  ];
  let out = ring;
  for (const [inside, cut] of edges) {
    const inp = out;
    out = [];
    for (let i = 0; i < inp.length; i++) {
      const a = inp[i], b = inp[(i + 1) % inp.length];
      if (inside(b)) { if (!inside(a)) out.push(cut(a, b)); out.push(b); }
      else if (inside(a)) out.push(cut(a, b));
    }
    if (!out.length) break;
  }
  return out;
}

function rdp(pts, tol) {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [s, e] = stack.pop();
    const [ax, ay] = pts[s], [bx, by] = pts[e];
    const dx = bx - ax, dy = by - ay, len = Math.hypot(dx, dy) || 1e-9;
    let max = 0, idx = -1;
    for (let i = s + 1; i < e; i++) {
      const d = Math.abs(dy * pts[i][0] - dx * pts[i][1] + bx * ay - by * ax) / len;
      if (d > max) { max = d; idx = i; }
    }
    if (max > tol && idx > -1) { keep[idx] = 1; stack.push([s, idx], [idx, e]); }
  }
  return pts.filter((_, i) => keep[i]);
}

const r1 = (n) => Math.round(n * 10) / 10;
const area = (ring) => Math.abs(ring.reduce((s, p, i) => { const q = ring[(i + 1) % ring.length]; return s + p[0] * q[1] - q[0] * p[1]; }, 0) / 2);

function toPath(geo, tol, minArea) {
  const polys = geo.type === "MultiPolygon" ? geo.coordinates : [geo.coordinates];
  let d = "";
  for (const poly of polys) {
    for (const ring of poly) {
      let pts = ring.map(([lon, lat]) => px(lon, lat));
      pts = clip(pts);
      if (pts.length < 3 || area(pts) < minArea) continue;
      pts = rdp(pts, tol);
      if (pts.length < 3) continue;
      d += "M" + pts.map(([x, y]) => `${r1(x)} ${r1(y)}`).join("L") + "Z";
    }
  }
  return d;
}

const getJson = async (file) => {
  const res = await fetch(NE + file);
  if (!res.ok) throw new Error(`${file}: ${res.status}`);
  return res.json();
};

const countries = await getJson("ne_10m_admin_0_countries.geojson");
const out = {};
for (const [key, name] of Object.entries(COUNTRIES)) {
  const f = countries.features.find((x) => (x.properties.ADMIN || "").includes(name));
  if (!f) throw new Error(`${name}: not found`);
  out[key] = key === "mne" ? toPath(f.geometry, 0.1, 0.5) : toPath(f.geometry, 0.4, 12);
  console.log(name.padEnd(24), `${(out[key].length / 1024).toFixed(1)} KB`);
}

const lakes = await getJson("ne_10m_lakes.geojson");
const skadar = lakes.features.find((x) => x.properties.name === "Lake Skadar");
if (!skadar) throw new Error("Lake Skadar not found");
out.lake = toPath(skadar.geometry, 0.1, 0.5);
console.log("Lake Skadar".padEnd(24), `${(out.lake.length / 1024).toFixed(1)} KB`);

const neighbours = ["alb", "kos", "srb", "bih", "hrv", "mkd"].map((k) => out[k]).join("");
fs.writeFileSync(
  new URL("./src/mapdata.mjs", import.meta.url),
  `// AUTO-GENERATED by make_map.mjs from Natural Earth (public domain). Do not edit by hand.\nexport const PROJ = ${JSON.stringify(PROJ)};\nexport const MNE_PATH = ${JSON.stringify(out.mne)};\nexport const NEIGHBOURS_PATH = ${JSON.stringify(neighbours)};
export const LAKE_PATH = ${JSON.stringify(out.lake)};\n`,
  "utf8"
);
console.log("wrote src/mapdata.mjs");
